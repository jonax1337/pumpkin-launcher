const PATHS = new Map<string, string>();

/** SVG-Pfad aus Zeilen: je Lauf von „#“ ein Rechteck (Zellen = viewBox-Einheiten). Gecacht. */
export function rowsPath(key: string, rows: readonly string[]) {
  let d = PATHS.get(key);
  if (d == null) {
    d = "";
    rows.forEach((r, y) => {
      let x = 0;
      while (x < r.length) {
        if (r[x] !== "#") { x++; continue; }
        let e = x;
        while (e < r.length && r[e] === "#") e++;
        d += `M${x} ${y}h${e - x}v1h${x - e}z`;
        x = e;
      }
    });
    PATHS.set(key, d);
  }
  return d;
}
