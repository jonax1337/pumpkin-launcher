export type IconName = keyof typeof ICON_DATA;
export const ICON_NAMES = Object.keys(ICON_DATA) as IconName[];

const PATHS = new Map<string, string>();

/** SVG-Pfad aus Zeilen: je Lauf von „#“ ein Rechteck (Zellen = viewBox-Einheiten). Gecacht. */
export function rowsPath(key: string, rows: readonly string[]) {
  let d = PATHS.get(key);
  if (d == null) {
    d = rowRuns(rows).map(({ x, y, length }) => `M${x} ${y}h${length}v1h${-length}z`).join("");
    PATHS.set(key, d);
  }
  return d;
}
